/**
 * guide.js —— 使用指南文案（首页弹窗与设置页共用）
 *
 * 粗体实现说明：小程序 WXML 不支持内联富文本标记，这里把文案中的 `**粗体**`
 * 解析为「分段数组 [{ t: 文本, b: 是否粗体 }]」，由页面用嵌套 wx:for 渲染，
 * 既能对关键信息做粗体强调，又保持源文案可直接阅读、易于维护。
 */
function parse(text) {
  const out = [];
  text.split(/\*\*(.+?)\*\*/g).forEach((seg, i) => {
    if (seg === '') return;
    out.push({ t: seg, b: i % 2 === 1 });
  });
  return out.length ? out : [{ t: '', b: false }];
}
